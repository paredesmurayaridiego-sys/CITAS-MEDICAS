    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
String codigoBuscado = txtCodigo.getText().trim();

if (codigoBuscado.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingrese el código del medicamento a buscar.");
    return;
}

File archivo = new File("medicamentos.txt");
if (!archivo.exists()) {
    JOptionPane.showMessageDialog(this, "No hay medicamentos registrados aún.");
    return;
}

boolean encontrado = false;
try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
    String linea;
    while ((linea = br.readLine()) != null) {
        String[] datos = linea.split(",");
        if (datos.length >= 5 && datos[0].trim().equalsIgnoreCase(codigoBuscado)) {
            txtNombre.setText(datos[1]);
            txtTipo.setText(datos[2]);
            txtPrecio.setText(datos[3]);
            txtStock.setText(datos[4]);
            JOptionPane.showMessageDialog(this, "Medicamento encontrado.");
            encontrado = true;
            break;
        }
    }
    if (!encontrado) {
        JOptionPane.showMessageDialog(this, "Medicamento no encontrado.");
    }
} catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Error al buscar: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
String codigo = txtCodigo.getText().trim();
String nombre = txtNombre.getText().trim();
String tipo = txtTipo.getText().trim();
String precio = txtPrecio.getText().trim();
String stock = txtStock.getText().trim();

if (codigo.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingrese el código del medicamento a modificar.");
    return;
}

File archivo = new File("medicamentos.txt");
if (!archivo.exists()) {
    JOptionPane.showMessageDialog(this, "El archivo no existe.");
    return;
}

List<String> lineas = new ArrayList<>();
boolean modificado = false;

try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
    String linea;
    while ((linea = br.readLine()) != null) {
        String[] datos = linea.split(",");
        if (datos.length >= 5 && datos[0].trim().equalsIgnoreCase(codigo)) {
            lineas.add(codigo + "," + nombre + "," + tipo + "," + precio + "," + stock);
            modificado = true;
        } else {
            lineas.add(linea);
        }
    }
} catch (IOException e) {
    JOptionPane.showMessageDialog(this, "Error al leer: " + e.getMessage());
    return;
}

if (modificado) {
    try (PrintWriter pw = new PrintWriter(new FileWriter(archivo, false))) {
        for (String l : lineas) {
            pw.println(l);
        }
        JOptionPane.showMessageDialog(this, "Medicamento modificado con éxito.");
        txtCodigo.setText("");
        txtNombre.setText("");
        txtTipo.setText("");
        txtPrecio.setText("");
        txtStock.setText("");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar los cambios: " + e.getMessage());
    }
} else {
    JOptionPane.showMessageDialog(this, "No se encontró un medicamento con ese código.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnModificarActionPerformed


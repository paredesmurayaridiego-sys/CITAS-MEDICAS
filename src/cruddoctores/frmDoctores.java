    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
String dni = txtDni.getText();

Doctor doctor = crud.buscarDoctor(dni);

if (doctor != null) {

    cmbTipo.setSelectedItem(doctor.getTipo());
    txtNombre.setText(doctor.getNombre());
    txtApellido.setText(doctor.getApellido());
    txtEspecialidad.setText(doctor.getEspecialidad());

} else {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Personal médico no encontrado."
    );
}
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
String tipo = cmbTipo.getSelectedItem().toString();
String dni = txtDni.getText();
String nombre = txtNombre.getText();
String apellido = txtApellido.getText();
String especialidad = txtEspecialidad.getText();

if (dni.isEmpty() || nombre.isEmpty() || apellido.isEmpty() || especialidad.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Complete todos los campos."
    );

    return;
}

boolean actualizado = crud.actualizarDoctor(
    dni,
    tipo,
    nombre,
    apellido,
    especialidad
);

if (actualizado) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Datos modificados correctamente."
    );

} else {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Personal médico no encontrado."
    );
}
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
String dni = txtDni.getText();

if (dni.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Ingrese el DNI."
    );

    return;
}

boolean eliminado = crud.eliminarDoctor(dni);

if (eliminado) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Registro eliminado correctamente."
    );

    txtNombre.setText("");
    txtApellido.setText("");
    txtDni.setText("");
    txtEspecialidad.setText("");
    cmbTipo.setSelectedIndex(0);

} else {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Personal médico no encontrado."
    );
}
    }//GEN-LAST:event_btnEliminarActionPerformed

